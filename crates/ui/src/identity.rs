//! Who the app says it is to the desktop. One ID everywhere: the Wayland app id, the
//! `.desktop` file's name, its `Icon` and `StartupWMClass`, so the desktop can match the
//! running window to its launcher and icon.
//!
//! Copied from `genetic_algo`'s `ui/src/identity.rs` and adapted.

use std::sync::Arc;

use eframe::egui::{self, IconData};

/// The name the window, the launcher and the about text show.
pub const APP_NAME: &str = "Photostacker";
/// The one ID of the app on the desktop.
pub const APP_ID: &str = "io.github.riccardogabellone.Photostacker";
/// The executable's name, set by `[[bin]]` in `crates/ui/Cargo.toml`.
pub const BINARY_NAME: &str = "Photostacker";

/// Generated by `assets/logo/export_icons.py`; 256 px is the largest size a title bar or
/// taskbar asks for.
const WINDOW_ICON_PNG: &[u8] = include_bytes!("../../../assets/icons/icon-256.png");

/// The logo shown inside the app: the 32 px icon, drawn from the two-frame variant that
/// stays legible at toolbar size.
const LOGO_PNG: &[u8] = include_bytes!("../../../assets/icons/icon-32.png");

/// The logo as a texture for the toolbar.
pub fn logo_texture(context: &egui::Context) -> egui::TextureHandle {
    let icon =
        eframe::icon_data::from_png_bytes(LOGO_PNG).expect("the bundled logo is a valid PNG");
    let image = egui::ColorImage::from_rgba_unmultiplied(
        [icon.width as usize, icon.height as usize],
        &icon.rgba,
    );
    context.load_texture("logo", image, egui::TextureOptions::LINEAR)
}

/// The icon for the window's title bar and taskbar entry.
///
/// On macOS the icon comes from the app bundle instead: setting one here would replace
/// the bundle's icon in the Dock, so an empty one is returned.
pub fn window_icon() -> Arc<IconData> {
    if cfg!(target_os = "macos") {
        return Arc::new(IconData::default());
    }
    Arc::new(
        eframe::icon_data::from_png_bytes(WINDOW_ICON_PNG)
            .expect("the bundled icon is a valid PNG"),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_bundled_icon_decodes_to_a_square_256_px_image() {
        let icon = eframe::icon_data::from_png_bytes(WINDOW_ICON_PNG).unwrap();
        assert_eq!((icon.width, icon.height), (256, 256));
        assert_eq!(icon.rgba.len(), 256 * 256 * 4);
    }

    #[test]
    fn the_desktop_entry_uses_the_app_id_everywhere() {
        // Reading the file by the ID's name also checks that the file is named after it.
        let path = format!(
            "{}/../../packaging/linux/{APP_ID}.desktop",
            env!("CARGO_MANIFEST_DIR")
        );
        let entry =
            std::fs::read_to_string(&path).unwrap_or_else(|error| panic!("{path}: {error}"));
        let field = |key: &str| {
            entry
                .lines()
                .find_map(|line| line.strip_prefix(key)?.strip_prefix('='))
                .unwrap_or_else(|| panic!("{key} is missing"))
        };
        assert_eq!(field("Name"), APP_NAME);
        assert_eq!(field("Icon"), APP_ID);
        assert_eq!(field("StartupWMClass"), APP_ID);
        assert_eq!(field("Exec"), BINARY_NAME);
    }
}
